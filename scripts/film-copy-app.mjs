// npm run film:app — copies the app's own stylesheet and DOM modules into film/app/ (unchanged), and the
// session markup from public/index.html into film/app/markup.js, so the film draws with the app's real code.
// test/film/appCopies.test.ts fails when a copy drifts from public/.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
export const APP_FILES = [
  'style.css',
  'js/arc.js', 'js/branchMap.js', 'js/branchMapView.js', 'js/captions.js', 'js/commands.js',
  'js/endLogic.js', 'js/endPage.js', 'js/render.js', 'js/transitions.js', 'js/voice.js',
];

/** The glass, the session view and the end view from public/index.html (no start screen, no scripts). */
export function sessionMarkup(html) {
  const body = html.slice(html.indexOf('<body>') + 6, html.indexOf('<script'));
  const start = body.indexOf('<main id="start-screen">');
  const startEnd = body.indexOf('</main>', start) + '</main>'.length;
  return (body.slice(0, start) + body.slice(startEnd)).trim();
}

if (process.argv[1] && import.meta.filename === path.resolve(process.argv[1])) {
  const out = path.join(root, 'film', 'app');
  mkdirSync(path.join(out, 'js'), { recursive: true });
  for (const f of APP_FILES) copyFileSync(path.join(root, 'public', f), path.join(out, f));
  const markup = sessionMarkup(readFileSync(path.join(root, 'public', 'index.html'), 'utf8'));
  writeFileSync(path.join(out, 'markup.js'), `// Generated by scripts/film-copy-app.mjs from public/index.html. Do not edit.\nexport const MARKUP = ${JSON.stringify(markup)};\n`);
  console.log(`copied ${APP_FILES.length} files and the session markup into film/app/`);
}
